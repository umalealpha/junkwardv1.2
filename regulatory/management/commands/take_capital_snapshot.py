"""
regulatory/management/commands/take_capital_snapshot.py

Compute and persist a regulatory capital snapshot. Run as a monthly cron
or on-demand before a NBFIRA submission.

    python manage.py take_capital_snapshot                      # uses today
    python manage.py take_capital_snapshot --as-of 2026-04-30
"""

from datetime import date, datetime

from django.contrib.auth.models import User
from django.core.management.base import BaseCommand, CommandError

from regulatory.services import take_snapshot
from django.utils import timezone


class Command(BaseCommand):
    help = 'Compute and persist a regulatory capital snapshot.'

    def add_arguments(self, parser):
        parser.add_argument('--as-of', help='Date (YYYY-MM-DD). Defaults to today.')
        parser.add_argument('--user',  default='admin',
                            help='Username to credit as preparer.')
        parser.add_argument('--notes', default='Auto-generated by management command.')

    def handle(self, *args, **opts):
        if opts.get('as_of'):
            try:
                as_of = datetime.strptime(opts['as_of'], '%Y-%m-%d').date()
            except ValueError:
                raise CommandError(f"Invalid --as-of: {opts['as_of']}")
        else:
            as_of = timezone.localdate()

        try:
            user = User.objects.get(username=opts['user'])
        except User.DoesNotExist:
            user = User.objects.filter(is_superuser=True).first()
            if user is None:
                raise CommandError('No user found to credit as preparer.')

        snap = take_snapshot(as_of=as_of, user=user, notes=opts['notes'])

        self.stdout.write(self.style.SUCCESS(
            f'\nSnapshot {snap.as_of_date}: '
            f'Available BWP {snap.available_capital:,.2f}, '
            f'Required BWP {snap.required_capital:,.2f}, '
            f'CAR {snap.car_pct}% — {snap.get_status_display()}'
        ))
