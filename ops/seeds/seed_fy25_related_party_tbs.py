def _get_admin():
    u = User.objects.filter(is_superuser=True).first() or User.objects.first()
    if not u: raise SystemExit('No User in DB')
    return u


def _ensure_period(d):
    period_name = d.strftime('%Y-%m')
    last_day = monthrange(d.year, d.month)[1]
    period, _ = FiscalPeriod.objects.get_or_create(
        period_name=period_name,
        defaults={
            'start_date': d.replace(day=1),
            'end_date':   d.replace(day=last_day),
            'status':     FiscalPeriod.Status.OPEN,
        },
    )
    if period.status != FiscalPeriod.Status.OPEN:
        period.status = FiscalPeriod.Status.OPEN
        period.save(update_fields=['status'])


def main():
    user = _get_admin()
    _ensure_period(ENTRY_DATE)

    for company_code, description, lines in ENTITY_JES:
        if JournalEntry.objects.filter(entry_date=ENTRY_DATE, description=description).exists():
            print(f'  skip {company_code}: already posted')
            continue
        company = Company.objects.filter(code=company_code).first()
        if not company:
            raise SystemExit(f'Company {company_code} not found. Run seed_companies_v3.py first.')

        with transaction.atomic():
            je = JournalEntry.objects.create(
                entry_date=ENTRY_DATE,
                description=description,
                source_type='import',
                journal_type='general',
                currency_code_id='BWP',
                exchange_rate=Decimal('1'),
                is_related_party=False,
                created_by=user,
                status='draft',
                company=company,
            )
            total_dr = total_cr = ZERO
            missing = []
            for code, dr, cr in lines:
                acct = Account.objects.filter(code=code).first()
                if not acct:
                    missing.append(code); continue
                d = Decimal(str(dr or 0)); c = Decimal(str(cr or 0))
                JournalEntryLine.objects.create(
                    journal_entry=je, account=acct,
                    debit_amount=d, credit_amount=c,
                    debit_bwp=d, credit_bwp=c,
                )
                total_dr += d; total_cr += c
            if missing:
                raise SystemExit(f'  {company_code}: missing accounts {missing[:8]}; run seed_coa_related_parties.py first')
            if total_dr != total_cr:
                raise SystemExit(f'  {company_code}: imbalanced Dr {total_dr} != Cr {total_cr}')
            je.post(user=user, _allow_direct=True)
            print(f'  +  {company_code:6s} {je.entry_number}  {len(lines):3d} lines  Dr=Cr={total_dr:>14,.2f}')


main()
