def main():
    Currency.objects.get_or_create(code='BWP', defaults={'name': 'Botswana Pula'})

    with transaction.atomic():
        # 1. Ensure all accounts exist (upsert with placeholder names if new)
        created = updated = 0
        for code, name, acct_type, sub_type, is_bank in NEW_ACCOUNTS:
            existing = Account.objects.filter(code=code).first()
            if existing:
                # Don't overwrite existing names (which may have been set properly)
                continue
            Account.objects.create(
                code=code, name=name,
                account_type=acct_type, sub_type=sub_type,
                is_bank_account=is_bank, is_active=True,
            )
            created += 1
        print(f'  Accounts: {created} created (existing kept as-is)')

        # 2. Ensure FY26 fiscal periods exist
        for ym in [(2025,7),(2025,8),(2025,9),(2025,10),(2025,11),(2025,12),(2026,1),(2026,2),(2026,3)]:
            period_name = f"{ym[0]}-{ym[1]:02d}"
            last_day = monthrange(ym[0], ym[1])[1]
            FiscalPeriod.objects.get_or_create(
                period_name=period_name,
                defaults={
                    'start_date': date(ym[0], ym[1], 1),
                    'end_date':   date(ym[0], ym[1], last_day),
                    'status':     FiscalPeriod.Status.OPEN,
                },
            )

        # 3. Get admin user
        user = User.objects.filter(is_superuser=True).first() or User.objects.first()
        if not user: raise SystemExit('No user in DB')

        # 4. Post 10 JEs
        for company_code, description, lines in ENTITY_JES:
            if JournalEntry.objects.filter(entry_date=ENTRY_DATE, description=description).exists():
                print(f'  skip {company_code}: already posted')
                continue
            company = Company.objects.filter(code=company_code).first()
            if not company:
                raise SystemExit(f'Company {company_code} missing — run seed_companies_v3.py first')

            je = JournalEntry.objects.create(
                entry_date=ENTRY_DATE, description=description,
                source_type='import', journal_type='general',
                currency_code_id='BWP', exchange_rate=Decimal('1'),
                is_related_party=False, created_by=user,
                status='draft', company=company,
            )
            total_dr = total_cr = ZERO
            for code, dr, cr in lines:
                acct = Account.objects.filter(code=code).first()
                if not acct:
                    raise SystemExit(f'Account {code} missing after upsert')
                d = Decimal(str(dr or 0)); c = Decimal(str(cr or 0))
                JournalEntryLine.objects.create(
                    journal_entry=je, account=acct,
                    debit_amount=d, credit_amount=c,
                    debit_bwp=d, credit_bwp=c,
                )
                total_dr += d; total_cr += c
            if total_dr != total_cr:
                raise SystemExit(f'  {company_code}: imbalanced {total_dr} != {total_cr}')
            je.post(user=user, _allow_direct=True)
            print(f'  +  {company_code:6s} {je.entry_number}  {len(lines):3d} lines  Dr=Cr={total_dr:>14,.2f}')


main()
